## Key Research Findings from Randomized Controlled Trial

The Consumer Financial Protection Bureau conducted a rigorous randomized controlled trial study on financial coaching with 945 participants across Miami and New York City, demonstrating measurable impacts on financial behavior and well-being.

### Financial Coaching vs Other Approaches

**Financial Coaching** differs from traditional financial education:
- Begins with CLIENT''S own goals (not predetermined curriculum)
- Strengths-based approach focusing on what clients do well
- Tailored, individualized support over time
- Emphasizes behavior change over knowledge transfer
- Average 2.7-3.1 sessions per client who attended

**Key Distinction**: Unlike counseling (crisis-response) or education (information-focused), coaching starts with the client''s priorities and adapts to their unique circumstances.

